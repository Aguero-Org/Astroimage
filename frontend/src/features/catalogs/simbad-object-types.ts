export function simbadObjectTypeName(
  otype?: string | null,
  otypeText?: string | null,
): string | null {
  if (otype) {
    const mapped = SIMBAD_OBJECT_TYPE_NAMES[otype];
    if (mapped) {
      return mapped;
    }
  }
  if (otypeText) {
    return otypeText;
  }
  return otype ?? null;
}
